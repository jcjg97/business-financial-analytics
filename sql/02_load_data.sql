Data Load Script
----------------
The financial_data.csv file is stored in the GitHub repository under:
data/raw/financial_data.csv

For security reasons, MySQL does not allow direct loading from remote URLs.
The data is imported locally using MySQL Workbench (Data Import Wizard).

Steps:
1. Download financial_data.csv from GitHub
2. Open MySQL Workbench
3. Go to Schemas in the left panel (Navigator), under the Schemas tab, expand business_financial_analytics
4. Expand the Tables list
4. Right-click on financial_data
5. Select Table Data Import Wizard
6. Choose the path where you saved the file financial_data.csv
7. Choose use existing table
